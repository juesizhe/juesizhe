def load(path):
    with open(path, "rb") as f:
        raw = f.read()
    # 归一为 LF 处理
    s = raw.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
    return s, raw

def save(path, s):
    # 统一回 CRLF 写盘
    out = s.replace("\n", "\r\n").encode("utf-8")
    with open(path, "wb") as f:
        f.write(out)

def apply(s, old, new, expect=1, label=""):
    c = s.count(old)
    if c != expect:
        raise SystemExit(f"[FAIL] {label}: 期望出现 {expect} 次，实际 {c} 次\n  old={old[:60]!r}")
    return s.replace(old, new)

