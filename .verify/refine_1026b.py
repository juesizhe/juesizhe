lines = raw.split(EOL)
orig = list(lines)


def idx(pref):
    r = [i for i in range(len(lines)) if lines[i].startswith(pref)]
    assert len(r) == 1, f"定位不唯一 {pref} -> {len(r)}"
    return r[0]


