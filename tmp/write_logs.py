EOL = "\r\n"

def load(rel):
    p = os.path.join(BASE, rel)
    raw = open(p, 'rb').read()
    assert raw.count(b'\r') == raw.count(b'\r\n'), f"{rel} 裸 CR 存在"
    return p, raw.decode('utf-8').split(EOL)

def save(p, lines):
    while lines and lines[-1].strip() == "":
        lines.pop()
    lines.append("")
    open(p, 'wb').write(EOL.join(lines).encode('utf-8'))
    nb = open(p, 'rb').read()
    assert nb.count(b'\r') == nb.count(b'\r\n'), f"{p} 写入后裸 CR"
    return len(nb)

