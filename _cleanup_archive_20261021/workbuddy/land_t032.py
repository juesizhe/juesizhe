def insert_before(L, anchor_prefix, block):
    idx = [i for i, l in enumerate(L) if l.startswith(anchor_prefix)]
    assert len(idx) == 1, "anchor %r -> %d" % (anchor_prefix, len(idx))
    i = idx[0]
    return L[:i] + block.rstrip('\n').split('\n') + [''] + L[i:]

