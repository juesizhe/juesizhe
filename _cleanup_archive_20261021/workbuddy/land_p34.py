def insert_before(path, anchor, text, encoding="utf-8"):
    with io.open(path, encoding=encoding) as f:
        lines = f.readlines()
    idx = None
    for i, ln in enumerate(lines):
        if ln.rstrip("\n") == anchor:
            idx = i
            break
    if idx is None:
        raise SystemExit("anchor not found in %s: %r" % (path, anchor[:40]))
    lines.insert(idx, text)
    with io.open(path, "w", encoding=encoding) as f:
        f.writelines(lines)
    print("inserted into", os.path.basename(path), "at line", idx + 1)


