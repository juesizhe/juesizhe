def read_crlf(p):
    raw = open(p, "rb").read()
    return raw.decode("utf-8").replace("\r\n", "\n"), raw

def write_crlf(p, text):
    data = text.replace("\n", "\r\n").encode("utf-8")
    open(p, "wb").write(data)

