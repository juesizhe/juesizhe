"②若一个**检测可靠、假阳性极低但自陈贫乏**的系统，在**三条通道被分别告知观察者之后**仍**未**获得更高的觉知归因（即归因完全由表层特征决定、证据无法校正归因），则第③维作为「可校正通道」失效；"
"③若错授或错夺道德地位的后果（误删、误授予、误免责）在真实部署中从未出现，则三条短路的共同体代价说失效。"
